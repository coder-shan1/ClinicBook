CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    slot_id BIGINT,
    status VARCHAR(20) NOT NULL,
    start_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    -- One active appointment per slot. Cancelled appointments detach the slot
    -- (slot_id = NULL) so the slot can be booked again; PostgreSQL allows many NULLs.
    CONSTRAINT uk_appointment_slot UNIQUE (slot_id),
    CONSTRAINT fk_appointment_patient FOREIGN KEY (patient_id) REFERENCES users (id),
    CONSTRAINT fk_appointment_doctor FOREIGN KEY (doctor_id) REFERENCES doctor (id),
    CONSTRAINT fk_appointment_slot FOREIGN KEY (slot_id) REFERENCES time_slot (id) ON DELETE SET NULL
);

CREATE INDEX idx_appointment_patient_start ON appointment (patient_id, start_at);
CREATE INDEX idx_appointment_doctor_start ON appointment (doctor_id, start_at);
CREATE INDEX idx_appointment_status ON appointment (status);
