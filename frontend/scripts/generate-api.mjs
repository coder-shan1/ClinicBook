// Generates TypeScript types from the backend OpenAPI spec.
//
//   node scripts/generate-api.mjs
//
// Source priority:
//   1. A committed spec at ../docs/api/openapi.json (offline / CI friendly), if present.
//   2. The backend's live OpenAPI endpoint. The backend (springdoc) exposes it at
//      http://localhost:8080/v3/api-docs by default (application.yml). Override the
//      URL with the OPENAPI_URL environment variable.
//
// Output: src/api/generated/schema.ts. Until real endpoints exist (Phase 1+) the
// spec is near-empty, so the hand-written types in src/api/types.ts remain in use.
// This script never fails the build: on any error it prints a message and exits 0.

import { existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendDir = path.resolve(__dirname, '..')
const specPath = path.resolve(frontendDir, '..', 'docs', 'api', 'openapi.json')
const outDir = path.resolve(frontendDir, 'src', 'api', 'generated')
const outPath = path.join(outDir, 'schema.ts')

const DEFAULT_OPENAPI_URL = 'http://localhost:8080/v3/api-docs'

function fail(message) {
  console.warn(`[generate-api] ${message}`)
  console.warn('[generate-api] Keeping the hand-written types in src/api/types.ts. Nothing was written.')
  process.exit(0)
}

let source
let specInput
try {
  if (existsSync(specPath)) {
    // Offline/CI path: read the committed spec file.
    specInput = specPath
    source = specPath
  } else {
    // Live path: fetch the backend's runtime OpenAPI document.
    const url = process.env.OPENAPI_URL ?? DEFAULT_OPENAPI_URL
    const res = await fetch(url)
    if (!res.ok) {
      throw new Error(`${url} returned HTTP ${res.status}`)
    }
    specInput = await res.json()
    source = url
  }

  // Defensive against openapi-typescript v7 (returns a string) and v6 (returns an AST).
  const { default: openapiTS, ast } = await import('openapi-typescript')
  const result = await openapiTS(specInput)
  const body = typeof result === 'string' ? result : ast(result)
  const header = `// GENERATED BY \`npm run generate-api\`. Source: ${source} — DO NOT EDIT.\n`

  await mkdir(outDir, { recursive: true })
  await writeFile(outPath, `${header}${body}\n`, 'utf8')
  console.log(`[generate-api] Wrote ${outPath} from ${source}`)
} catch (err) {
  const detail = err && err.message ? err.message : String(err)
  if (existsSync(specPath)) {
    fail(`Could not parse ${specPath}: ${detail}`)
  } else {
    fail(
      `No committed spec at ../docs/api/openapi.json and the backend OpenAPI endpoint ` +
        `(${process.env.OPENAPI_URL ?? DEFAULT_OPENAPI_URL}) is unreachable: ${detail}. ` +
        `Start the backend (mvn spring-boot:run) or commit a spec.`,
    )
  }
}
