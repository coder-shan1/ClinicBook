// Generates the TypeScript API contract from the backend OpenAPI spec.
//
//   npm run generate-api
//
// Source priority:
//   1. OPENAPI_SPEC — explicit path to a spec file.
//   2. A committed spec at ../docs/api/openapi.json (offline / CI friendly).
//   3. The backend's live OpenAPI endpoint (`OPENAPI_URL`, default
//      http://localhost:8080/v3/api-docs).
//
// Output: src/api/generated/schema.ts. The file is committed so a fresh checkout
// type-checks and builds without requiring the backend. Re-run this script whenever
// docs/api/openapi.json changes.
//
// This script never fails the build: on any error it prints a message and exits 0,
// leaving the previously generated file untouched.

import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendDir = path.resolve(__dirname, '..')
const committedSpecPath = path.resolve(frontendDir, '..', 'docs', 'api', 'openapi.json')
const envSpec = process.env.OPENAPI_SPEC ? path.resolve(process.env.OPENAPI_SPEC.trim()) : null
const specPath = envSpec ?? committedSpecPath
const outDir = path.resolve(frontendDir, 'src', 'api', 'generated')
const outPath = path.join(outDir, 'schema.ts')

const DEFAULT_OPENAPI_URL = 'http://localhost:8080/v3/api-docs'

function fail(message) {
  console.warn(`[generate-api] ${message}`)
  console.warn('[generate-api] No file was written.')
  process.exit(0)
}

/** A stable, machine-independent label for the header comment. */
function describeSource(source) {
  if (/^https?:/i.test(source)) return source
  const relative = path.relative(frontendDir, source)
  return relative.startsWith('..') ? relative.split(path.sep).join('/') : relative
}

let source
let specInput
try {
  if (existsSync(specPath)) {
    // Offline/CI path: read the committed spec file.
    specInput = JSON.parse(await readFile(specPath, 'utf8'))
    source = specPath
  } else {
    // Live path: fetch the backend's runtime OpenAPI document.
    const url = process.env.OPENAPI_URL ?? DEFAULT_OPENAPI_URL
    const res = await fetch(url)
    if (!res.ok) {
      throw new Error(`${url} returned HTTP ${res.status}`)
    }
    specInput = await res.json()
    source = url
  }

  // Defensive against openapi-typescript v7 (astToString) and v6 (ast).
  const openapiModule = await import('openapi-typescript')
  const openapiTS = openapiModule.default
  const result = await openapiTS(specInput)
  const body =
    typeof result === 'string'
      ? result
      : openapiModule.astToString
        ? openapiModule.astToString(result)
        : openapiModule.ast
          ? openapiModule.ast(result)
          : String(result)
  const header = `// GENERATED BY \`npm run generate-api\`. Source: ${describeSource(source)} — DO NOT EDIT.\n`

  await mkdir(outDir, { recursive: true })
  await writeFile(outPath, `${header}${body}\n`, 'utf8')
  console.log(
    `[generate-api] Wrote ${path.relative(frontendDir, outPath)} from ${describeSource(source)}`,
  )
} catch (err) {
  const detail = err && err.message ? err.message : String(err)
  if (existsSync(specPath)) {
    fail(`Could not parse ${describeSource(specPath)}: ${detail}`)
  } else {
    fail(
      `No committed spec at ${describeSource(committedSpecPath)} and the backend OpenAPI ` +
        `endpoint (${process.env.OPENAPI_URL ?? DEFAULT_OPENAPI_URL}) is unreachable: ${detail}. ` +
        'Start the backend (mvn spring-boot:run) or commit a spec.',
    )
  }
}
