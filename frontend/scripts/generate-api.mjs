// Generates TypeScript types from the backend OpenAPI spec.
//
//   node scripts/generate-api.mjs
//
// Reads ../docs/api/openapi.json (relative to this frontend package) and writes
// src/api/generated/schema.ts. The OpenAPI spec is owned by the backend; until it
// exists this script prints a friendly message and exits cleanly so it never
// breaks CI or `npm install`. Once the spec lands, run this after every API change
// and verify the output against the current openapi-typescript API.

import { existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const frontendDir = path.resolve(__dirname, '..')
const specPath = path.resolve(frontendDir, '..', 'docs', 'api', 'openapi.json')
const outDir = path.resolve(frontendDir, 'src', 'api', 'generated')
const outPath = path.join(outDir, 'schema.ts')

if (!existsSync(specPath)) {
  console.warn(`[generate-api] OpenAPI spec not found at ${specPath}`)
  console.warn('[generate-api] Using hand-written types in src/api/types.ts until the backend ships the spec.')
  process.exit(0)
}

// Defensive against openapi-typescript v7 (returns a string) and v6 (returns an AST).
const { default: openapiTS, ast } = await import('openapi-typescript')
const result = await openapiTS(specPath)
const body = typeof result === 'string' ? result : ast(result)
const header = '// GENERATED BY `npm run generate-api` FROM docs/api/openapi.json — DO NOT EDIT.\n'

await mkdir(outDir, { recursive: true })
await writeFile(outPath, `${header}${body}\n`, 'utf8')
console.log(`[generate-api] Wrote ${outPath}`)
