import { describe, it, expect } from 'vitest'
import { screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { Route, Routes } from 'react-router-dom'
import { http, HttpResponse } from 'msw'
import { renderWithProviders } from '../../test/utils'
import DoctorDetailPage from '../../pages/DoctorDetailPage'
import { server } from '../../mocks/node'
import { users } from '../../mocks/db'

/** Render the page at /doctors/1 with the given signed-in user. */
function renderPage(user?: (typeof users)[number] | null) {
  return renderWithProviders(
    <Routes>
      <Route path="/doctors/:id" element={<DoctorDetailPage />} />
    </Routes>,
    { initialEntries: ['/doctors/1'], user },
  )
}

/** Pick tomorrow so the 09:00 mock slot is always in the future. */
async function selectTomorrow() {
  const user = userEvent.setup()
  const dateButtons = await screen.findAllByRole('button', { name: /^Select / })
  await user.click(dateButtons[1])
  return user
}

describe('DoctorDetailPage', () => {
  it('renders doctor profile details and available time slots', async () => {
    renderPage()

    // Doctor profile details
    expect(await screen.findByRole('heading', { name: /dr\. ada okonkwo/i })).toBeInTheDocument()
    expect(screen.getByText('Cardiology')).toBeInTheDocument()
    expect(screen.getByText('$120.00')).toBeInTheDocument()
    expect(
      screen.getByText(/board-certified cardiologist focused on preventive heart health/i),
    ).toBeInTheDocument()

    // Booking section: calendar + slots generated by MSW
    expect(await screen.findByRole('heading', { name: /book an appointment/i })).toBeInTheDocument()
    expect(screen.getByRole('group', { name: /available dates/i })).toBeInTheDocument()
    expect(await screen.findByText('09:00')).toBeInTheDocument()
  })

  it('shows the doctor rating and patient reviews', async () => {
    renderPage()

    expect(await screen.findByRole('heading', { name: /patient reviews/i })).toBeInTheDocument()
    expect(await screen.findByText('Sam P.')).toBeInTheDocument()
    expect(screen.getByText(/dr\. okonkwo explained everything clearly/i)).toBeInTheDocument()
    expect(screen.getAllByText(/4\.7 out of 5/i).length).toBeGreaterThan(0)
  })

  it('asks anonymous visitors to log in before booking', async () => {
    renderPage(null)

    expect(await screen.findByRole('link', { name: /log in/i })).toBeInTheDocument()
    expect(
      await screen.findByText(/to book an appointment with dr\. ada okonkwo/i),
    ).toBeInTheDocument()
  })

  it('books a slot after confirmation', async () => {
    renderPage(users[0])
    const user = await selectTomorrow()

    const slotButton = await screen.findByRole('button', { name: /book 09:00 to 09:30/i })
    await user.click(slotButton)

    expect(screen.getByRole('heading', { name: /confirm your booking/i })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /confirm booking/i }))

    expect(await screen.findByText(/is pending confirmation/i)).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /view my appointments/i })).toBeInTheDocument()
  })

  it('refreshes the slots with a friendly message when the slot was just taken (409)', async () => {
    server.use(
      http.post('/api/v1/appointments', () => {
        return HttpResponse.json(
          {
            timestamp: new Date().toISOString(),
            status: 409,
            error: 'SLOT_TAKEN',
            message: 'This slot has already been booked',
            path: '/api/v1/appointments',
            fieldErrors: [],
          },
          { status: 409 },
        )
      }),
    )

    renderPage(users[0])
    const user = await selectTomorrow()

    await user.click(await screen.findByRole('button', { name: /book 09:00 to 09:30/i }))
    await user.click(screen.getByRole('button', { name: /confirm booking/i }))

    expect(await screen.findByRole('alert')).toHaveTextContent(/just taken by someone else/i)
  })

  it('renders error state when doctor is not found (404)', async () => {
    server.use(
      http.get('/api/v1/doctors/:id', () => {
        return HttpResponse.json(
          {
            timestamp: new Date().toISOString(),
            status: 404,
            error: 'NOT_FOUND',
            message: 'Doctor 999 not found',
            path: '/api/v1/doctors/999',
            fieldErrors: [],
          },
          { status: 404 },
        )
      }),
    )

    renderWithProviders(
      <Routes>
        <Route path="/doctors/:id" element={<DoctorDetailPage />} />
      </Routes>,
      { initialEntries: ['/doctors/999'] },
    )

    expect(await screen.findByRole('alert')).toHaveTextContent(/doctor 999 not found/i)
  })

  it('renders empty state when doctor has no slots on selected date', async () => {
    server.use(
      http.get('/api/v1/doctors/:id/slots', () => {
        return HttpResponse.json([])
      }),
    )

    renderWithProviders(
      <Routes>
        <Route path="/doctors/:id" element={<DoctorDetailPage />} />
      </Routes>,
      { initialEntries: ['/doctors/1'] },
    )

    expect(
      await screen.findByText(/no available appointment slots found on this date/i),
    ).toBeInTheDocument()
  })
})
